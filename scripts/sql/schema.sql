CREATE TABLE `admin_operation_log` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '自增主键',
  `admin_user_id` BIGINT UNSIGNED NOT NULL COMMENT '逻辑关联 admin_user.id',
  `username_snapshot` VARCHAR(64) NOT NULL COMMENT '操作时用户名称，账号删除后仍可读',
  `operation_type` VARCHAR(12) NOT NULL COMMENT 'login/create/update/delete/status/review/export/import/reset/other',
  `action_name` VARCHAR(100) NOT NULL COMMENT '具体动作展示',
  `target_type` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '资源类别；可无具体目标',
  `target_id` BIGINT UNSIGNED NULL DEFAULT NULL COMMENT '对应 target_type 的逻辑业务目标，不是物理外键',
  `target_summary` VARCHAR(500) NULL DEFAULT NULL COMMENT '当时目标展示摘要',
  `ip_address` VARBINARY(16) NOT NULL COMMENT 'INET6_ATON 编码，兼容 IPv4/IPv6',
  `request_id` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '请求关联标识，不包含凭据',
  `operation_result` VARCHAR(8) NOT NULL COMMENT 'success/failure',
  `details` JSON NULL DEFAULT NULL COMMENT '脱敏结构化变化/摘要，不含密码验证码密钥',
  `occurred_at` DATETIME(3) NOT NULL COMMENT 'UTC',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后更新时间，UTC',
  `deleted_at` DATETIME(3) NULL DEFAULT NULL COMMENT '逻辑删除时间；NULL 为未删除，UTC',
  PRIMARY KEY (`id`),
  KEY `idx_log_type_time` (`deleted_at`,`operation_type`,`occurred_at`,`id`),
  KEY `idx_log_user_time` (`admin_user_id`,`deleted_at`,`occurred_at`,`id`),
  KEY `idx_log_target` (`target_type`,`target_id`,`occurred_at`),
