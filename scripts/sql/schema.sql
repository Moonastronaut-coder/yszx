  CONSTRAINT `ck_admin_operation_log_2` CHECK (operation_result IN ('success','failure')),
  CONSTRAINT `ck_admin_operation_log_3` CHECK (OCTET_LENGTH(ip_address) IN (4,16)),
  CONSTRAINT `ck_admin_operation_log_4` CHECK (`admin_user_id` IS NULL OR `admin_user_id` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci ROW_FORMAT=DYNAMIC COMMENT='后台操作日志';

