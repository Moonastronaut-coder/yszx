SET NAMES utf8mb4 COLLATE utf8mb4_0900_as_ci;
SET SESSION time_zone = '+00:00';

-- 文件基础设施：持久文件元信息
CREATE TABLE `file_asset` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '自增主键',
  `storage_provider` VARCHAR(32) NOT NULL COMMENT '存储适配标识，不含密钥',
  `bucket_name` VARCHAR(128) NULL DEFAULT NULL COMMENT '对象存储桶；本地存储可空',
  `object_key` VARCHAR(512) NOT NULL COMMENT '不可变存储对象标识，相对存储根目录',
  `original_name` VARCHAR(255) NOT NULL COMMENT '上传文件原始名称',
  `media_type` VARCHAR(100) NOT NULL COMMENT '服务端确认的媒体类型',
  `size_bytes` BIGINT UNSIGNED NOT NULL COMMENT '文件大小，字节',
  `sha256` BINARY(32) NOT NULL COMMENT '文件内容摘要，仅完整性与排查，不强制全局去重',
  `asset_kind` VARCHAR(20) NOT NULL COMMENT 'avatar/logo/default_avatar',
  `uploaded_by_learner_id` BIGINT UNSIGNED NULL DEFAULT NULL COMMENT '逻辑关联 learner.id',
  `uploaded_by_admin_id` BIGINT UNSIGNED NULL DEFAULT NULL COMMENT '逻辑关联 admin_user.id',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后更新时间，UTC',
  `deleted_at` DATETIME(3) NULL DEFAULT NULL COMMENT '逻辑删除时间；NULL 为未删除，UTC',
  PRIMARY KEY (`id`),
  KEY `idx_asset_owner_learner` (`uploaded_by_learner_id`,`deleted_at`),
  KEY `idx_asset_owner_admin` (`uploaded_by_admin_id`,`deleted_at`),
  CONSTRAINT `ck_file_asset_1` CHECK (asset_kind IN ('avatar','logo','default_avatar')),
  CONSTRAINT `ck_file_asset_2` CHECK ((uploaded_by_learner_id IS NOT NULL AND uploaded_by_admin_id IS NULL) OR (uploaded_by_learner_id IS NULL AND uploaded_by_admin_id IS NOT NULL)),
  CONSTRAINT `ck_file_asset_3` CHECK (`uploaded_by_learner_id` IS NULL OR `uploaded_by_learner_id` > 0),
  CONSTRAINT `ck_file_asset_4` CHECK (`uploaded_by_admin_id` IS NULL OR `uploaded_by_admin_id` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci ROW_FORMAT=DYNAMIC COMMENT='持久文件元信息';

-- M02/M11：学员账号与个人资料
CREATE TABLE `learner` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '自增主键',
  `phone` CHAR(11) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '手机号登录；逻辑删除后仍保留唯一占用（DB1A）',
  `email` VARCHAR(254) COLLATE utf8mb4_0900_as_ci NULL DEFAULT NULL COMMENT '选填邮箱；空串转 NULL，登录匹配不区分大小写',
  `password_hash` VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '单向密码散列，不存原始密码',
  `nickname` VARCHAR(64) NOT NULL COMMENT '可编辑展示用户名，不要求唯一',
  `gender` VARCHAR(8) NOT NULL DEFAULT 'secret' COMMENT 'male/female/secret',
  `avatar_file_id` BIGINT UNSIGNED NULL DEFAULT NULL COMMENT '逻辑关联 file_asset.id',
  `status` TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '1 启用，0 禁用',
  `auth_version` BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '会话撤销/认证状态版本，Redis 会话记录同版本',
  `last_login_at` DATETIME(3) NULL DEFAULT NULL COMMENT '从未登录时为空，UTC',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后更新时间，UTC',
  `deleted_at` DATETIME(3) NULL DEFAULT NULL COMMENT '逻辑删除时间；NULL 为未删除，UTC',
  PRIMARY KEY (`id`),
  KEY `idx_learner_status_created` (`deleted_at`,`status`,`created_at`,`id`),
  UNIQUE KEY `uk_learner_phone` (`phone`),
  UNIQUE KEY `uk_learner_email` (`email`),
  CONSTRAINT `ck_learner_1` CHECK (phone REGEXP '^[0-9]{11}$'),
  CONSTRAINT `ck_learner_2` CHECK (gender IN ('male','female','secret')),
  CONSTRAINT `ck_learner_3` CHECK (status IN (0,1)),
  CONSTRAINT `ck_learner_4` CHECK (auth_version >= 1),
  CONSTRAINT `ck_learner_5` CHECK (email IS NULL OR CHAR_LENGTH(TRIM(email)) > 0),
  CONSTRAINT `ck_learner_6` CHECK (CHAR_LENGTH(TRIM(nickname)) > 0),
  CONSTRAINT `ck_learner_7` CHECK (`avatar_file_id` IS NULL OR `avatar_file_id` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci ROW_FORMAT=DYNAMIC COMMENT='学员账号与个人资料';

